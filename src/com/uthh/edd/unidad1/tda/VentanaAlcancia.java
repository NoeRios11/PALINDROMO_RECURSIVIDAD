    private void btndepositsarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btndepositsarActionPerformed
        try {
            // convierte la cantidad ingresada a float y realiza el deposito
            float cantidad = Float.parseFloat(txtdepositar.getText());
            mialcancia.depositar_moneda(cantidad);
            actualizar_saldo();
        } catch (Exception e) {
            // muestra mensaje de error si ingresan letras o dejan vacia la caja
            JOptionPane.showMessageDialog(this, "ingresa un monto numerico ");
        }
    }//GEN-LAST:event_btndepositsarActionPerformed

