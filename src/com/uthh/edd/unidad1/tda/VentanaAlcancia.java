    private void btncalculaproyeccionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btncalculaproyeccionActionPerformed
        try {
            // lee los dias ingresados en la caja de texto
            int dias = Integer.parseInt(txtdias.getText());         
            // lee la cuota diaria ingresada en la nueva caja de texto
            float cuotaDiaria = Float.parseFloat(txtcuotadiaria.getText());        
            // realiza el calculo de proyeccion ahorro de forma recursiva
            float resultado = mialcancia.proyeccion_ahorro(dias, cuotaDiaria);      
            // muestra el resultado 
            JOptionPane.showMessageDialog(this, "ahorrando $" + cuotaDiaria + " diarios durante " + dias + " días tendras: $" + resultado);
                            
        } catch (Exception e) {
            // muestra mensaje de error si alguna de las cajas esta vacia o tiene texto
            JOptionPane.showMessageDialog(this, "ingresa numeros validos en los dias y en la cuota diaria");
        }
    }//GEN-LAST:event_btncalculaproyeccionActionPerformed

